import { chromium } from 'playwright';
const base='https://staging-umbraco.splatdev.tech';
const browser=await chromium.launch({headless:true, executablePath:'/usr/bin/chromium-browser', args:['--no-sandbox','--disable-gpu','--disable-dev-shm-usage']});
const context=await browser.newContext({viewport:{width:1440,height:1000},recordVideo:{dir:'qa-runs/video'}});
const page=await context.newPage();
page.on('console', m=>console.log('CONSOLE',m.type(),m.text()));
await page.goto(base+'/umbraco',{waitUntil:'networkidle',timeout:60000});
console.log('initial',page.url(),await page.title());
console.log('inputs',await page.locator('input').count(),'buttons',await page.locator('button').allTextContents());
const email=process.env.U17_STAGING_ADMIN_EMAIL, pw=process.env.U17_STAGING_ADMIN_PASSWORD;
for(const el of await page.locator('input').all()){console.log('input',await el.getAttribute('type'),await el.getAttribute('name'),await el.getAttribute('id'));}
const emailInput=page.locator('input[type=email],input[name*=email i],input[name*=user i]').first();
const passInput=page.locator('input[type=password]').first();
await emailInput.fill(email); await passInput.fill(pw);
await page.getByRole('button').filter({hasText:/log\s*in|sign\s*in/i}).first().click();
await page.waitForTimeout(8000); await page.waitForLoadState('networkidle').catch(()=>{});
console.log('after',page.url(),await page.title());
console.log((await page.locator('body').innerText()).slice(0,3000));
await page.screenshot({path:'qa-runs/00-authenticated-home.png',fullPage:true});
const text=(await page.locator('body').innerText());
console.log('sections',await page.locator('a,button,[role=button],umb-section, uui-menu-item').allTextContents());
console.log('links',await page.locator('a').evaluateAll(es=>es.map(e=>({text:e.textContent,href:e.href})).slice(0,100)));
if(!text.includes('Email Templates')) throw new Error('Email Templates section not visible');
await page.getByText('Email Templates',{exact:true}).first().click(); await page.waitForTimeout(3000); await page.screenshot({path:'qa-runs/01-templates.png',fullPage:true});
await page.getByText('Style Settings',{exact:true}).click(); await page.waitForTimeout(2000); await page.screenshot({path:'qa-runs/02-style.png',fullPage:true});
await page.getByText('Templates',{exact:true}).click(); await page.waitForTimeout(2000);
const buttons=await page.getByRole('button').allTextContents(); console.log('template buttons',buttons);
const create=page.getByRole('button',{name:/create|new|add/i}).first(); if(await create.count()) await create.click(); else await page.getByText(/create template|new template/i).first().click();
await page.waitForTimeout(1500); await page.screenshot({path:'qa-runs/03-template-create.png',fullPage:true});
await page.getByRole('button',{name:/preview/i}).click().catch(()=>{}); await page.waitForTimeout(1500); await page.screenshot({path:'qa-runs/04-preview.png',fullPage:true});
await context.close(); await browser.close();
